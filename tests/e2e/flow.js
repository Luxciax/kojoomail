// Kojoo Mail 端到端：启动真实程序（独立数据目录），经 WebView2 调试端口操作界面
//   node flow.js <exe> <输出目录> <邮箱> <密码>     （可选环境变量 KJM_AI_KEY：顺便测 AI）
const { chromium } = require('playwright-core')
const { spawn } = require('child_process')
const fs = require('fs')
const os = require('os')
const path = require('path')

const [exe, out, user, pass] = process.argv.slice(2)
const PORT = 9333
const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), 'kjm-e2e-'))
fs.mkdirSync(out, { recursive: true })
const issues = []
const SUBJ = 'Kojoo Mail 自测 ' + Date.now().toString(36)
const log = (...a) => console.log(new Date().toISOString().slice(11, 19), ...a)

async function main() {
  const proc = spawn(exe, [], {
    // 假的客户端 ID：只为让一键登录的界面显示出来，测试不会真去点登录
    env: { ...process.env, KOJOOMAIL_DATA: dataDir, KOJOOMAIL_CDP_PORT: String(PORT), KOJOOMAIL_GOOGLE_CLIENT_ID: 'e2e-google', KOJOOMAIL_MS_CLIENT_ID: 'e2e-ms' },
    stdio: ['ignore', 'pipe', 'pipe'],
  })
  proc.stderr.on('data', (d) => fs.appendFileSync(path.join(out, 'app.log'), d))
  proc.stdout.on('data', (d) => fs.appendFileSync(path.join(out, 'app.log'), d))
  let browser
  for (let i = 0; i < 40 && !browser; i++) {
    await new Promise((r) => setTimeout(r, 500))
    browser = await chromium.connectOverCDP(`http://127.0.0.1:${PORT}`).catch(() => null)
  }
  if (!browser) throw new Error('连不上 WebView2 调试端口')
  const page = browser.contexts()[0].pages()[0]
  page.on('pageerror', (e) => issues.push('JS 错误：' + e.message))
  // 正文 iframe 无脚本 + 拦远程图片是预期行为，这两类控制台报错不算问题
  page.on('console', (m) => { const t = m.text(); if (m.type() === 'error' && !/about:srcdoc|img-src data:/.test(t)) issues.push('控制台：' + t.slice(0, 200)) })
  await page.setViewportSize({ width: 1280, height: 820 }).catch(() => {})
  const shot = (n) => page.screenshot({ path: path.join(out, n + '.png') })
  const step = async (name, fn) => {
    const t0 = Date.now()
    try { await fn(); log('✓', name, `${Date.now() - t0}ms`) } catch (e) { issues.push(`步骤失败 ${name}：${e.message.split('\n')[0]}`); log('✗', name, e.message.split('\n')[0]); await shot('fail-' + name).catch(() => {}) }
  }

  await step('欢迎页', async () => {
    await page.waitForSelector('.welcome', { timeout: 15000 })
    await shot('01-welcome')
  })
  await step('一键登录界面（Gmail / Outlook）', async () => {
    const m = await page.locator('.welcome .pv:has-text("Outlook") .m').innerText()
    if (m !== '一键登录') issues.push('欢迎页 Outlook 不是一键登录：' + m)
    await page.click('.welcome .pv:has-text("Outlook")')
    await page.waitForSelector('.sheet .btn.primary:has-text("在浏览器中登录")')
    if (await page.locator('#a-pass').count()) issues.push('Outlook 一键登录时还显示了密码框')
    await page.waitForTimeout(500) // 等弹窗动画结束再截图
    await shot('01b-oauth-outlook')
    await page.click('.sheet .pv:has-text("Gmail")')
    await page.waitForSelector('.sheet :text("用谷歌账号登录")')
    await page.click('.sheet .btn:has-text("改用应用专用密码")')
    await page.waitForSelector('#a-pass')
    await page.waitForTimeout(300)
    await shot('01c-gmail-apppass')
    await page.click('.sheet .btn:has-text("改用一键登录")')
    await page.waitForSelector('.sheet .btn.primary:has-text("在浏览器中登录")')
    await page.click('.sheet .sh-foot .btn:has-text("取消")')
    await page.waitForSelector('.sheet', { state: 'detached' })
  })
  await step('欢迎页的教程', async () => {
    await page.click('.welcome .btn:has-text("先看看怎么用")')
    await page.waitForSelector('.sheet.wide :text("三步上手")')
    await page.waitForTimeout(400)
    await shot('01d-guide')
    await page.keyboard.press('Escape')
    await page.waitForSelector('.sheet', { state: 'detached' })
  })
  await step('添加账号', async () => {
    await page.click('.welcome .pv:has-text("kojoo.co")')
    await page.waitForSelector('.sheet')
    await page.fill('#a-email', user)
    await page.fill('#a-pass', pass)
    await page.fill('#a-label', '测试 · kojoo')
    await shot('02-add-account')
    await page.click('.sheet .btn.primary')
    await page.waitForSelector('.mrow[data-id]', { timeout: 60000 })
    await page.waitForTimeout(2500)
    await shot('03-inbox')
    const n = await page.locator('.mrow[data-id]').count()
    if (n < 5) issues.push(`收件箱只有 ${n} 封`)
    log('收件箱', n, '封')
  })
  await step('读信', async () => {
    await page.click('.mrow[data-id]:has-text("Inquiry")')
    await page.waitForSelector('.reader h2', { timeout: 30000 })
    await page.waitForTimeout(1200)
    await shot('04-read')
  })
  await step('营销邮件：预览没有 CSS，远程图片被拦截', async () => {
    const prev = await page.locator('.mrow[data-id]:has-text("双十一") .prev').innerText()
    if (/color|\{|\}/.test(prev)) issues.push('预览里出现了 CSS：' + prev)
    await page.click('.mrow[data-id]:has-text("双十一")')
    await page.waitForSelector('.remote-note', { timeout: 20000 })
    await shot('05-remote-blocked')
  })
  if (process.env.KJM_AI_KEY) {
    await step('设置 AI 密钥', async () => {
      await page.click('[aria-label="设置"]')
      await page.click('.set-nav .nav:has-text("AI 与模型")')
      await page.fill('#ai-key', process.env.KJM_AI_KEY)
      await page.click('.set-main .btn:has-text("保存")')
      await page.locator('.set-main').getByText(/已连接 ·|失败：/).waitFor({ timeout: 30000 })
      await shot('06-settings-ai')
      const t = await page.locator('.set-main').innerText()
      if (!t.includes('已连接')) issues.push('AI 测试连接没通过')
      await page.click('[aria-label="返回邮件"]')
    })
    await step('AI 批注', async () => {
      await page.click('.mrow[data-id]:has-text("Inquiry")')
      await page.waitForSelector('.ai-card', { timeout: 15000 })
      const btn = page.locator('.ai-card .btn:has-text("让 AI 分析")')
      if (await btn.count()) await btn.click()
      await page.waitForSelector('.ai-card .ai-summary, .ai-card .reply-box', { timeout: 90000 })
      await page.waitForTimeout(800)
      await shot('07-ai-card')
    })
    await step('翻译邮件（译文、缓存、还原原文）', async () => {
      const bodyText = async () => ((await page.locator('.mail-frame').count()) ? page.frameLocator('.mail-frame').locator('body').innerText() : page.locator('.reader-scroll .mail-sheet, .reader-scroll > div:last-child').last().innerText())
      const orig = await bodyText()
      await page.click('.tr-note .btn:has-text("翻译成中文")')
      await page.locator('.tr-note').getByText(/已翻译|翻译没成功/).waitFor({ timeout: 120000 })
      await page.waitForTimeout(500)
      await shot('07b-translated')
      const note = await page.locator('.tr-note').innerText()
      if (note.includes('翻译没成功')) issues.push('翻译失败：' + note)
      else {
        const tr = await bodyText()
        if (tr === orig) issues.push('翻译后正文没有变化')
        await page.click('.tr-note .btn:has-text("显示原文")')
        await page.waitForTimeout(500)
        if ((await bodyText()) !== orig) issues.push('点「显示原文」后正文没有还原')
        // 再翻一次：应命中缓存，很快出结果
        const t0 = Date.now()
        await page.click('.tr-note .btn:has-text("翻译成中文")')
        await page.locator('.tr-note').getByText('已翻译').waitFor({ timeout: 20000 })
        log('二次翻译用时', Date.now() - t0, 'ms（命中缓存应很快）')
      }
    })
  }
  await step('写信并发给自己', async () => {
    await page.click('[aria-label="写邮件"]')
    await page.waitForSelector('.compose')
    await page.fill('#c-to', user)
    await page.keyboard.press('Enter')
    await page.fill('.compose input[aria-label="主题"]', SUBJ)
    await page.fill('.compose textarea', '你好，这是 **自测**：\n\n- 第一点\n- 第二点')
    await shot('08-compose')
    await page.click('.compose .btn.primary')
    await page.waitForSelector('.toast:has-text("已发送")', { timeout: 60000 })
    await shot('09-sent')
  })
  await step('收到自己发的信', async () => {
    await page.waitForSelector(`.mrow[data-id]:has-text("${SUBJ}")`, { timeout: 90000 })
    await page.click(`.mrow[data-id]:has-text("${SUBJ}")`)
    await page.waitForSelector(`.reader h2:has-text("${SUBJ}")`, { timeout: 20000 })
    await page.waitForTimeout(1000)
    await shot('10-received')
  })
  await step('归档再撤销', async () => {
    const before = await page.locator('.mrow[data-id]').count()
    await page.keyboard.press('e')
    await page.waitForSelector('.toast:has-text("撤销")', { timeout: 5000 })
    if ((await page.locator('.mrow[data-id]').count()) !== before - 1) issues.push('归档后列表没少一封')
    await page.click('.toast button:has-text("撤销")')
    await page.waitForTimeout(1500)
    if ((await page.locator('.mrow[data-id]').count()) !== before) issues.push('撤销归档后邮件没回来')
  })
  await step('归档落到服务器（无归档文件夹时自动创建）', async () => {
    await page.click(`.mrow[data-id]:has-text("${SUBJ}")`)
    await page.keyboard.press('e')
    await page.waitForSelector('.toast:has-text("撤销")', { timeout: 5000 })
    await page.waitForTimeout(9000)
    const err = await page.locator('.toast.err').count()
    if (err) issues.push('归档后出现错误提示：' + (await page.locator('.toast.err').first().innerText()))
    await page.click('.side [aria-label="展开文件夹"] >> nth=0').catch(() => {})
    await page.waitForTimeout(800)
    await shot('10b-archived')
    if (!(await page.locator('.side .nav:has-text("归档")').count())) issues.push('侧栏没有出现归档文件夹')
    // 归档文件夹里应该正好一封（本地占位和服务器新副本对上了，没有重复也没丢）
    await page.click('.side .nav.sub:has-text("归档")')
    await page.waitForTimeout(1500)
    const n = await page.locator(`.mrow[data-id]:has-text("${SUBJ}")`).count()
    if (n !== 1) issues.push(`归档文件夹里这封邮件有 ${n} 封（应为 1）`)
    await shot('10c-archive-folder')
    await page.click('.side .nav:has-text("全部收件箱")')
    await page.waitForTimeout(800)
  })
  await step('常用分类和 AI 处理', async () => {
    await page.click('[aria-label="设置"]')
    await page.click('.set-nav .nav:has-text("账号")')
    await page.click('.set-main .btn[aria-pressed]:has-text("订阅")')
    await page.waitForSelector('.set-main .btn.primary[aria-pressed="true"]:has-text("订阅")')
    await page.click('.set-main .seg button:has-text("只分类")')
    await page.waitForSelector('.set-main .seg button.on:has-text("只分类")')
    await page.waitForTimeout(300)
    await shot('10d-account-focus')
    await page.click('.set-main .seg button:has-text("完整")')
    await page.click('.set-nav .nav:has-text("使用教程")')
    await page.waitForSelector('.set-main :text("三步上手")')
    await shot('10e-guide-settings')
    await page.click('[aria-label="返回邮件"]')
    await page.click('.side .nav:has-text("全部收件箱")')
    const tabs = await page.locator('.list-head .seg button, .seg[role=tablist] button').allInnerTexts()
    if (tabs.join('|') !== '全部|未读|待办|订阅') issues.push('页签不对：' + tabs.join('|'))
    await page.click('.seg button:has-text("订阅")')
    await page.waitForTimeout(1200)
    const subs = await page.locator('.mrow[data-id]').allInnerTexts()
    if (!subs.some((t) => t.includes('双十一'))) issues.push('「订阅」页签里没有那封营销邮件')
    if (subs.some((t) => t.includes('Inquiry'))) issues.push('「订阅」页签里混进了询盘邮件')
    await shot('10f-tab-subscription')
    await page.click('.seg button:has-text("全部")')
    await page.waitForTimeout(500)
  })
  await step('右键菜单', async () => {
    await page.click('.mrow[data-id] >> nth=1', { button: 'right' })
    await page.waitForSelector('.menu')
    await shot('11-context-menu')
    await page.keyboard.press('Escape')
  })
  await step('待办页', async () => {
    await page.click('.side .nav:has-text("待办")')
    await page.waitForTimeout(800)
    await shot('12-todo')
  })
  await step('深色', async () => {
    await page.click('[aria-label="设置"]')
    await page.click('.set-main button:has-text("深色")')
    await page.waitForTimeout(400)
    await shot('13-settings-dark')
    await page.click('[aria-label="返回邮件"]')
    await page.click('.side .nav:has-text("全部收件箱")')
    await page.waitForTimeout(500)
    await page.click('.mrow[data-id]:has-text("Inquiry")')
    await page.waitForTimeout(1500)
    await shot('14-dark-read')
    await page.click('[aria-label="设置"]')
    await page.click('.set-main button:has-text("浅色")')
    await page.click('[aria-label="返回邮件"]')
  })
  await step('资源占用', async () => {
    await page.waitForTimeout(8000)
    const { execSync } = require('child_process')
    const ps = execSync(`powershell -NoProfile -ExecutionPolicy Bypass -File "${path.join(__dirname, 'mem.ps1')}" -root ${proc.pid}`).toString()
    log(ps.trim())
    fs.writeFileSync(path.join(out, 'memory.txt'), ps)
  })
  if (process.env.KJM_KEEP) {
    // 保留数据目录给 idle.sh 测空闲内存（账号留着，测完记得删目录）
    console.log('DATA_DIR=' + dataDir)
    console.log(issues.length ? '问题：\n' + issues.join('\n') : '没有发现问题')
    await browser.close().catch(() => {})
    proc.kill()
    return setTimeout(() => process.exit(0), 500)
  }
  await step('删除测试账号', async () => {
    await page.click('[aria-label="设置"]')
    await page.click('.set-nav .nav:has-text("账号")')
    page.once('dialog', (d) => d.accept())
    await page.click('.set-main .btn.danger')
    await page.waitForSelector('.welcome', { timeout: 10000 })
  })
  console.log(issues.length ? '问题：\n' + issues.join('\n') : '没有发现问题')
  await browser.close().catch(() => {})
  proc.kill()
  setTimeout(() => process.exit(0), 500)
}
main().catch((e) => { console.error(e); process.exit(1) })
